/**
 * Fetches the Ossido vs Next.js benchmark results the `/benchmarks` page renders,
 * and writes the committed `src/content/benchmarks.generated.ts`.
 *
 * Results live in the ossido-benchmarks repo under `results/<ossido-version>/` -
 * one folder per Ossido release, each with a machine-readable `results.json`
 * (throughput / latency / streaming) and `memory.json` (memory-efficiency sweep).
 *
 * Which version is picked:
 *   - If `OSSIDO_VERSION` is set (it is, in `.env`) and that folder exists in the
 *     repo, that release is pinned - so the site's numbers track the Ossido version
 *     it documents.
 *   - Otherwise the latest release folder (semver-aware, prereleases last) is used.
 *
 * The output is committed (like `api-reference.generated.ts` and the baked cube
 * geometry) so dev, typecheck and offline builds work without the network. It's
 * refreshed on every production build via `build.prebuild` in ossido.config.ts; if
 * the fetch fails (offline / CI without network), the existing committed file is
 * kept rather than clobbered, so a build never breaks on a network blip.
 *
 * Run with: bun run build-benchmarks (or OSSIDO_VERSION=x.y.z bun run build-benchmarks)
 */
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'content', 'benchmarks.generated.ts');

const REPO = 'ossido-labs/ossido-benchmarks';
const BRANCH = 'main';
const CONTENTS_API = `https://api.github.com/repos/${REPO}/contents/results?ref=${BRANCH}`;
const raw = (version: string, file: string): string =>
  `https://raw.githubusercontent.com/${REPO}/${BRANCH}/results/${version}/${file}`;
const tree = (version: string): string =>
  `https://github.com/${REPO}/tree/${BRANCH}/results/${version}`;

/** Compare two release folder names: numeric major.minor.patch, then a release
 *  (no `-prerelease`) outranks a prerelease, then prereleases compare numerically
 *  (so the `.20260822...Z` timestamp orders betas of the same base version). */
function compareVersions(a: string, b: string): number {
  const parse = (v: string): { nums: Array<number>; pre: string } => {
    const [core, ...preParts] = v.split('-');
    return {
      nums: core.split('.').map((n) => Number.parseInt(n, 10) || 0),
      pre: preParts.join('-'),
    };
  };
  const pa = parse(a);
  const pb = parse(b);
  for (let i = 0; i < 3; i++) {
    const d = (pa.nums[i] ?? 0) - (pb.nums[i] ?? 0);
    if (d !== 0) return d;
  }
  if (pa.pre === pb.pre) return 0;
  if (!pa.pre) return 1; // a is a full release -> newer
  if (!pb.pre) return -1; // b is a full release -> newer
  return pa.pre.localeCompare(pb.pre, undefined, { numeric: true });
}

const GH_HEADERS: Record<string, string> = {
  Accept: 'application/vnd.github+json',
  'User-Agent': 'ossido-site-build',
  ...(process.env.GITHUB_TOKEN
    ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` }
    : {}),
};

async function listVersions(): Promise<Array<string>> {
  const res = await fetch(CONTENTS_API, { headers: GH_HEADERS });
  if (!res.ok)
    throw new Error(`GitHub contents API ${res.status} for ${CONTENTS_API}`);
  const entries = (await res.json()) as Array<{ name: string; type: string }>;
  return entries.filter((e) => e.type === 'dir').map((e) => e.name);
}

async function fetchJson(url: string): Promise<unknown | null> {
  const res = await fetch(url, {
    headers: { 'User-Agent': 'ossido-site-build' },
  });
  if (res.status === 404) return null; // e.g. a version with no memory sweep
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`);
  return res.json();
}

async function main(): Promise<void> {
  const pinned = process.env.OSSIDO_VERSION?.trim();
  const versions = await listVersions();
  if (versions.length === 0)
    throw new Error('no result folders found in the benchmarks repo');

  const version =
    pinned && versions.includes(pinned)
      ? pinned
      : [...versions].sort(compareVersions).at(-1)!;

  if (pinned && version !== pinned) {
    console.warn(
      `  ! OSSIDO_VERSION=${pinned} has no benchmark results yet - falling back to latest (${version}).`,
    );
  }

  const results = await fetchJson(raw(version, 'results.json'));
  if (!results) throw new Error(`results.json missing for ${version}`);
  const memory = await fetchJson(raw(version, 'memory.json'));

  const bundle = {
    version,
    source: tree(version),
    repo: `https://github.com/${REPO}`,
    results,
    memory,
  };

  const body = `/**
 * GENERATED by scripts/build-benchmarks.ts - do not edit by hand.
 * Regenerate with: bun run build-benchmarks
 *
 * Snapshot of the ossido-benchmarks results for Ossido ${version}.
 */
import type { BenchmarkBundle } from './benchmarks';

export const BENCHMARKS: BenchmarkBundle = ${JSON.stringify(bundle, null, 2)} as const;
`;

  writeFileSync(OUT, body);
  const memNote = memory ? 'with memory sweep' : 'no memory sweep';
  console.log(
    `Wrote benchmarks for Ossido ${version} (${memNote}) -> src/content/benchmarks.generated.ts`,
  );
}

main().catch((err) => {
  const message = err instanceof Error ? err.message : String(err);
  if (existsSync(OUT)) {
    console.warn(
      `  ! build-benchmarks: ${message}\n    Keeping the existing src/content/benchmarks.generated.ts.`,
    );
    process.exit(0); // don't break the build on a network blip
  }
  console.error(
    `build-benchmarks failed and no committed snapshot exists: ${message}`,
  );
  process.exit(1);
});
